package ch.uetlib.core.image.util;

import com.drew.imaging.ImageProcessingException;

import org.apache.commons.io.FileUtils;
import org.imgscalr.Scalr;

import java.awt.image.BufferedImage;
import java.io.ByteArrayInputStream;
import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Collection;
import java.util.List;

import javax.imageio.ImageIO;

public final class ImageUtils {

    private ImageUtils() {}

    private static String formatFrameNumberType(
            final int frameNumber, final int totalFrames, final ImageType mediaType) {
        final var format =
                "%"
                        + Math.max(1, ((Double) Math.log10(totalFrames)).intValue())
                        + "d."
                        + mediaType.toString();
        return String.format(format, frameNumber);
    }

    /** Be sure to call {@link BufferedImage#flush} once you don't need the image anymore. */
    public static BufferedImage imageFromBytes(final byte[] imageBytes)
            throws IOException, ImageProcessingException {
        try (final var imageStreamForImageInfo = new ByteArrayInputStream(imageBytes);
                final var imageStreamForImage = new ByteArrayInputStream(imageBytes)) {
            final var imageInfo = ExifTransform.readImageInformation(imageStreamForImageInfo);
            return ExifTransform.transformImage(
                    ImageIO.read(imageStreamForImage),
                    ExifTransform.getExifTransformation(imageInfo),
                    imageInfo);
        }
    }

    public static byte[] imageToBytes(final BufferedImage image, final String formatName)
            throws IOException {
        try (final var outputStream = new ByteArrayOutputStream()) {
            ImageIO.write(image, formatName, outputStream);
            return outputStream.toByteArray();
        }
    }

    public static byte[] imageToBytesAndFlush(final BufferedImage image, final String formatName)
            throws IOException {
        final var bytes = imageToBytes(image, formatName);
        image.flush();
        return bytes;
    }

    /**
     * Writes the given images to files in the given directory. The filenames are generated by the
     * given function.
     *
     * @param mediaType the media type of the images. Should be something like "png" or "jpg" that
     *     can be used as a file extension
     */
    public static List<Path> writeImageListToFiles(
            final Collection<BufferedImage> bufferedImages,
            final ImageType mediaType,
            final Path outputDirPath)
            throws IOException {
        final var paths = new ArrayList<Path>(bufferedImages.size());
        final var iterator = bufferedImages.iterator();
        for (var i = 0; i < bufferedImages.size(); i++) {
            final var path =
                    outputDirPath.resolve(
                            formatFrameNumberType(i, bufferedImages.size(), mediaType));
            paths.add(path);
            final var bufferedImage = iterator.next();
            ImageIO.write(bufferedImage, mediaType.imageIOType(), path.toFile());
        }
        return paths;
    }

    public static List<Path> writeImageBytesListToFiles(
            final Collection<byte[]> imagesData,
            final ImageType mediaType,
            final Path outputDirPath)
            throws IOException {
        final var paths = new ArrayList<Path>(imagesData.size());
        final var iterator = imagesData.iterator();
        for (var i = 0; i < imagesData.size(); i++) {
            final var path =
                    outputDirPath.resolve(formatFrameNumberType(i, imagesData.size(), mediaType));
            paths.add(path);
            final var imageData = iterator.next();
            FileUtils.writeByteArrayToFile(path.toFile(), imageData);
        }
        return paths;
    }

    /**
     * @param originalImage the input image. This image will be flushed after scaling
     */
    public static BufferedImage scaleAndFlush(
            final BufferedImage originalImage, final int imageSize) {

        final var scaledImage = Scalr.resize(originalImage, imageSize);
        originalImage.flush();

        return scaledImage;
    }

    public static byte[] createScaledImage(
            final byte[] imageBytes, final int imageSize, final String formatName)
            throws ImageProcessingException, IOException {
        return imageToBytesAndFlush(
                scaleAndFlush(imageFromBytes(imageBytes), imageSize), formatName);
    }
}
